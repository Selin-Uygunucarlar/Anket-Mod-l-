ALTER TABLE ONLY public.survey_question
    ADD CONSTRAINT pk_survey_question PRIMARY KEY (survey_id, question_id);

ALTER TABLE ONLY public.survey_assignment
    ADD CONSTRAINT pk_survey_assignment PRIMARY KEY (id);

ALTER TABLE ONLY public.answer
    ADD CONSTRAINT pk_answer PRIMARY KEY (id);

ALTER TABLE ONLY public.survey_message
    ADD CONSTRAINT pk_survey_message PRIMARY KEY (id);

ALTER TABLE ONLY public.lookup_value
    ADD CONSTRAINT pk_lookup_value PRIMARY KEY (id);

-- ===========================================================================
-- Tekillik kısıtları
-- ===========================================================================

-- Aynı kategoride aynı değer iki kez tanımlanamaz (MariaDB: uq_secenek_kategori_deger).
ALTER TABLE ONLY public.lookup_value
    ADD CONSTRAINT uq_lookup_value_category_value UNIQUE (category, value);

-- ===========================================================================
-- Bütünlük kısıtları (CHECK)
-- MariaDB tarafında bu tablolarda CHECK YOKTU; aşağıdaki tek CHECK bilinçli bir
-- EKLEMEDİR ve raporlanmıştır.
-- ===========================================================================

-- Tamamlanma tutarlılığı: completed_at doluysa durum 'tamamlandı' OLMAK ZORUNDADIR.
-- Uygulama bugün zaten ikisini birlikte yazıyor (cevaplari_kaydet); bu CHECK o
-- garantiyi DB'de de zorlar, böylece yarım kalmış bir yazma tutarsız satır bırakamaz.
-- Ters yön (durum 'tamamlandı' iken completed_at dolu olmalı) BİLEREK zorlanmadı:
-- ileride tarihsiz tamamlama gerekirse şema engel olmasın.
ALTER TABLE ONLY public.survey_assignment
    ADD CONSTRAINT ck_survey_assignment_completion
    CHECK (completed_at IS NULL OR status = 'tamamlandı');

-- ===========================================================================
-- Yabancı anahtarlar — HOST tablolarına (public.staff)
-- staff üretimde host'a aittir; anket modülü ona BAĞLANIR, onu yönetmez.
-- ===========================================================================

-- Anketi oluşturan personel. ON DELETE SET NULL: personel kaydı gitse bile anket
-- KAYBOLMAZ, yalnızca "kim oluşturdu" bilgisi düşer.
ALTER TABLE ONLY public.survey
    ADD CONSTRAINT fk_survey_created_by FOREIGN KEY (created_by)
    REFERENCES public.staff(staff_id) ON UPDATE CASCADE ON DELETE SET NULL;

-- Soruyu hazırlayan personel. Aynı gerekçe: soru havuzu personel silinince boşalmaz.
ALTER TABLE ONLY public.question
    ADD CONSTRAINT fk_question_prepared_by FOREIGN KEY (prepared_by)
    REFERENCES public.staff(staff_id) ON UPDATE CASCADE ON DELETE SET NULL;

-- Anketin atandığı personel. ON DELETE CASCADE (MariaDB ile birebir): personel
-- kaydı silinirse ona ait atama ve -- zincirleme -- cevapları da gider; yetim
-- atama satırı kalmaz.
ALTER TABLE ONLY public.survey_assignment
    ADD CONSTRAINT fk_survey_assignment_staff FOREIGN KEY (staff_id)
    REFERENCES public.staff(staff_id) ON UPDATE CASCADE ON DELETE CASCADE;

-- ===========================================================================
-- Yabancı anahtarlar — modül içi
-- Tümü MariaDB'deki ON DELETE/ON UPDATE davranışlarıyla birebirdir.
-- ===========================================================================

-- NOT: MariaDB'deki fk_soru_anket (Soru.anket_id -> Anket) karşılığı YOKTUR; kolonun
-- kendisi taşınmadığı için FK de kurulmaz. Anket-soru bağı survey_question'dadır.

ALTER TABLE ONLY public.question_option
    ADD CONSTRAINT fk_question_option_question FOREIGN KEY (question_id)
    REFERENCES public.question(id) ON UPDATE CASCADE ON DELETE CASCADE;

ALTER TABLE ONLY public.survey_question
    ADD CONSTRAINT fk_survey_question_survey FOREIGN KEY (survey_id)
    REFERENCES public.survey(id) ON UPDATE CASCADE ON DELETE CASCADE;

ALTER TABLE ONLY public.survey_question
    ADD CONSTRAINT fk_survey_question_question FOREIGN KEY (question_id)
    REFERENCES public.question(id) ON UPDATE CASCADE ON DELETE CASCADE;

ALTER TABLE ONLY public.survey_assignment
    ADD CONSTRAINT fk_survey_assignment_survey FOREIGN KEY (survey_id)
    REFERENCES public.survey(id) ON UPDATE CASCADE ON DELETE CASCADE;

ALTER TABLE ONLY public.answer
    ADD CONSTRAINT fk_answer_assignment FOREIGN KEY (assignment_id)
    REFERENCES public.survey_assignment(id) ON UPDATE CASCADE ON DELETE CASCADE;

ALTER TABLE ONLY public.answer
    ADD CONSTRAINT fk_answer_question FOREIGN KEY (question_id)
    REFERENCES public.question(id) ON UPDATE CASCADE ON DELETE CASCADE;

-- ON DELETE SET NULL (MariaDB ile birebir): şık silinse bile cevap satırı durur,
-- yalnızca hangi şıkkın seçildiği bilgisi düşer.
ALTER TABLE ONLY public.answer
    ADD CONSTRAINT fk_answer_selected_option FOREIGN KEY (selected_option_id)
    REFERENCES public.question_option(id) ON UPDATE CASCADE ON DELETE SET NULL;

ALTER TABLE ONLY public.survey_message
    ADD CONSTRAINT fk_survey_message_survey FOREIGN KEY (survey_id)
    REFERENCES public.survey(id) ON UPDATE CASCADE ON DELETE CASCADE;

-- ===========================================================================
-- İndeksler
-- PostgreSQL, MariaDB/InnoDB'nin aksine FK kolonlarını KENDİLİĞİNDEN indekslemez.
-- MariaDB'de FK'lerle birlikte oluşan KEY'lerin karşılıkları burada açıkça kurulur.
-- survey_question.survey_id için indeks YOKTUR: bileşik PK'nin ilk kolonu olduğundan
-- PK indeksi zaten onu karşılar (gereksiz ikinci indeks kurulmaz).
-- ===========================================================================

CREATE INDEX ix_survey_access_group_id ON public.survey (access_group_id);
CREATE INDEX ix_survey_created_by ON public.survey (created_by);
CREATE INDEX ix_question_prepared_by ON public.question (prepared_by);
CREATE INDEX ix_question_option_question_id ON public.question_option (question_id);
CREATE INDEX ix_survey_question_question_id ON public.survey_question (question_id);
CREATE INDEX ix_survey_assignment_survey_id ON public.survey_assignment (survey_id);
CREATE INDEX ix_survey_assignment_staff_id ON public.survey_assignment (staff_id);
CREATE INDEX ix_answer_assignment_id ON public.answer (assignment_id);
CREATE INDEX ix_answer_question_id ON public.answer (question_id);
CREATE INDEX ix_answer_selected_option_id ON public.answer (selected_option_id);
CREATE INDEX ix_survey_message_survey_id ON public.survey_message (survey_id);

