-- Runtime hesabının yetkileri (en az yetki)
-- savronik_app YALNIZCA veri okur/yazar: DDL (CREATE/ALTER/DROP) VERİLMEZ.
-- NEDEN AYRICA GRANT: 001'deki "GRANT ON ALL TABLES" yalnızca O AN var olan
-- nesneleri kapsar; sonradan gelen bu tablolar oradan yetki DEVRALMAZ. Her migration
-- kendi tablolarını kendisi GRANT'lar.
-- ===========================================================================

GRANT SELECT, INSERT, UPDATE, DELETE ON
    public.survey,
    public.question,
    public.question_option,
    public.survey_question,
    public.survey_assignment,
    public.answer,
    public.survey_message,
    public.lookup_value
TO savronik_app;

-- Identity sequence'leri. NOT: identity kolonlarda nextval dahili çağrılır ve
-- PostgreSQL ayrı bir sequence yetkisi ARAMAZ; yine de açıkça verilir ki hesabın
-- yetki yüzeyi tek bakışta okunsun ve ileride serial'a dönen bir kolon INSERT'i
-- sessizce düşürmesin. survey_question'ın identity kolonu yoktur (bileşik PK).
GRANT USAGE, SELECT ON SEQUENCE
    public.survey_id_seq,
    public.question_id_seq,
    public.question_option_id_seq,
    public.survey_assignment_id_seq,
    public.answer_id_seq,
    public.survey_message_id_seq,
    public.lookup_value_id_seq
TO savronik_app;
